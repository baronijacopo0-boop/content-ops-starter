/**
 * Generates SQL from the TypeScript reference data so DB and app never drift:
 *  - supabase/migrations/20261027000005_reference_data.sql (categories + brands, needed in production)
 *  - supabase/seed.sql (demo market_items comparables for development / market metrics)
 * Run: npx tsx scripts/generate-sql.ts
 */
import { writeFileSync } from 'node:fs';
import { BRANDS, CATEGORIES } from '../src/lib/domain/constants';
import { buildComparables, buildDealFeed } from '../src/lib/marketplace/data/mock-catalog';

const q = (v: string | number | null | undefined | string[]): string => {
  if (v === null || v === undefined) return 'null';
  if (Array.isArray(v)) return `array[${v.map((x) => q(x)).join(',')}]::text[]`;
  if (typeof v === 'number') return String(v);
  return `'${v.replace(/'/g, "''")}'`;
};

const ref = [
  '-- Generated by scripts/generate-sql.ts – do not edit by hand.',
  '-- Reference data: garment categories and brand priors used by pricing & Deal Score.',
  'insert into public.categories (id, label, singular, base_price, speed_days, sort_order) values',
  CATEGORIES.map(
    (c, i) => `  (${q(c.value)}, ${q(c.label)}, ${q(c.singular)}, ${c.basePrice}, ${c.speedDays}, ${i})`,
  ).join(',\n'),
  'on conflict (id) do update set label = excluded.label, singular = excluded.singular, base_price = excluded.base_price, speed_days = excluded.speed_days, sort_order = excluded.sort_order;',
  '',
  'insert into public.brands (name, demand, price_multiplier, tier, niches) values',
  BRANDS.map((b) => `  (${q(b.name)}, ${b.demand}, ${b.priceMultiplier}, ${q(b.tier)}, ${q(b.niches)})`).join(
    ',\n',
  ),
  'on conflict (name) do update set demand = excluded.demand, price_multiplier = excluded.price_multiplier, tier = excluded.tier, niches = excluded.niches;',
  '',
].join('\n');
writeFileSync('supabase/migrations/20261027000005_reference_data.sql', ref);

const now = new Date('2026-10-01T00:00:00Z');
const comps = buildComparables(now);
const deals = buildDealFeed(now);
const rows = [
  ...comps.map(
    (c) =>
      `  ('demo', ${q(c.id)}, ${q(`${c.brand} ${c.model ?? ''}`.trim())}, ${q(c.brand)}, ${q(c.category)}, ${q(c.model)}, ${q(c.size)}, ${q(c.condition)}, ${c.price}, ${q(c.soldPrice)}, ${c.daysOnMarket}, ${q(c.listedAt)}, ${q(c.soldAt)})`,
  ),
  ...deals.map(
    (d) =>
      `  ('demo', ${q(d.externalId)}, ${q(d.title)}, ${q(d.brand)}, ${q(d.category)}, ${q(d.model)}, ${q(d.size)}, ${q(d.condition)}, ${d.price}, null, 0, ${q(d.listedAt)}, null)`,
  ),
];
const seed = [
  "-- Generated by scripts/generate-sql.ts – demo market data (marketplace = 'demo'), safe to skip in production.",
  'insert into public.market_items (marketplace, external_id, title, brand, category, model, size, condition, price, sold_price, days_on_market, listed_at, sold_at) values',
  rows.join(',\n'),
  'on conflict (marketplace, external_id) do nothing;',
  '',
  'select public.refresh_market_prices();',
  '',
].join('\n');
writeFileSync('supabase/seed.sql', seed);
console.log(
  `reference: ${CATEGORIES.length} categories, ${BRANDS.length} brands · seed: ${rows.length} market items`,
);
